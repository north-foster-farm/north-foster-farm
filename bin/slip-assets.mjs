#!/usr/bin/env node
// Writes netlify/functions/lib/slip-assets.mjs: what the customer's
// packing slip (#292) embeds in its PDF. Aller regular and bold
// (static/fonts/aller-*.woff, WOFF 1.0, which lib/ttf.mjs reads) as
// base64, and the site's hen and wordmark (assets/images/logo-mark.svg
// and logo.svg) as PDF path operators in the SVG's own units. The
// files stay the one source: test/packing.test.mjs fails when this
// module no longer matches them, and running this again fixes it.
//
//   node bin/slip-assets.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const OUT = "netlify/functions/lib/slip-assets.mjs";

const font = (name) => readFileSync(
  join(root, "static/fonts", `aller-${name}.woff`)
).toString("base64");

// SVG path data -> PDF path operators, every point absolute. The
// logos use M, L, H, V, C, S and Z, absolute or relative; any other
// command is an error here, never a wrong drawing.
const ARGS = { m: 2, l: 2, h: 1, v: 1, c: 6, s: 4, z: 0 };

const pathOps = (d) => {
  const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g);
  const out = [];
  const n = (v) => String(Math.round(v * 10) / 10);
  let [x, y, x0, y0, cx, cy] = [0, 0, 0, 0, null, null];
  let cmd = "";
  let i = 0;

  const point = (rel, px, py) => (rel ? [x + px, y + py] : [px, py]);

  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) cmd = tokens[i++];
    else if (cmd === "m") cmd = "l";
    else if (cmd === "M") cmd = "L";

    const low = cmd.toLowerCase();
    const rel = cmd === low;

    if (!(low in ARGS)) throw new Error(`slip-assets: path command ${cmd}`);

    const a = tokens.slice(i, i + ARGS[low]).map(Number);

    i += ARGS[low];
    if (low === "z") {
      out.push("h");
      [x, y] = [x0, y0];
      [cx, cy] = [null, null];
      continue;
    }
    if (low === "m" || low === "l") {
      [x, y] = point(rel, a[0], a[1]);
      if (low === "m") [x0, y0] = [x, y];
      out.push(`${n(x)} ${n(y)} ${low}`);
      [cx, cy] = [null, null];
    } else if (low === "h" || low === "v") {
      if (low === "h") x = rel ? x + a[0] : a[0];
      else y = rel ? y + a[0] : a[0];
      out.push(`${n(x)} ${n(y)} l`);
      [cx, cy] = [null, null];
    } else {
      // C takes two controls then the end; S reflects the last
      // curve's second control for its first.
      const first = low === "s"
        ? (cx === null ? [x, y] : [2 * x - cx, 2 * y - cy])
        : point(rel, a[0], a[1]);
      const k = low === "s" ? 0 : 2;
      const second = point(rel, a[k], a[k + 1]);
      const end = point(rel, a[k + 2], a[k + 3]);

      out.push(`${[...first, ...second, ...end].map(n).join(" ")} c`);
      [cx, cy] = second;
      [x, y] = end;
    }
  }

  return out.join(" ");
};

// An SVG's viewBox and its paths, each filled by its own rule.
const art = (name) => {
  const svg = readFileSync(join(root, "assets/images", `${name}.svg`), "utf8");
  const [x, y, w, h] = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/)
    .map(Number);
  const paths = [...svg.matchAll(/<path\b([^>]*)>/g)].map(([, attrs]) =>
    `${pathOps(attrs.match(/\bd="([^"]+)"/)[1])} ${
      /fill-rule="evenodd"/.test(attrs) ? "f*" : "f"}`);

  return { box: [x, y, w, h], ops: paths.join(" ") };
};

// A long string as lines that keep to 80 columns.
const pieces = (s) => {
  const out = [];

  for (let i = 0; i < s.length; i += 72) out.push(`  "${s.slice(i, i + 72)}",`);

  return out.join("\n");
};

const artModule = (name, a) => `export const ${name} = {
  box: ${JSON.stringify(a.box)},
  ops: [
${pieces(a.ops).replace(/^/gm, "  ")}
  ].join(""),
};`;

const HEAD = "// Generated by bin/slip-assets.mjs from static/fonts/\n"
  + "// aller-regular.woff and aller-bold.woff, and assets/images/\n"
  + "// logo-mark.svg and logo.svg. Do not edit; run the script again.";

export const render = () => `${HEAD}

export const regular = [
${pieces(font("regular"))}
].join("");

export const bold = [
${pieces(font("bold"))}
].join("");

${artModule("mark", art("logo-mark"))}

${artModule("wordmark", art("logo"))}
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(root, OUT), render());
  console.log(`Wrote ${OUT}`);
}
