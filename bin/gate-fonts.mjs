#!/usr/bin/env node
// Writes netlify/functions/lib/gate-fonts.mjs: the site's Aller,
// regular and bold (static/fonts/aller-*.woff2), as base64 for the
// gate's pages (#294). Those pages can fetch nothing of the site's, so
// they carry the fonts as data: URIs. The font files stay the one
// source: test/gate-page.test.mjs fails when this module no longer
// matches them, and running this again fixes it.
//
//   node bin/gate-fonts.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const OUT = "netlify/functions/lib/gate-fonts.mjs";

const font = (name) => readFileSync(
  join(root, "static/fonts", `aller-${name}.woff2`)
).toString("base64");

// A long string as lines that keep to 80 columns.
const pieces = (s) => {
  const out = [];

  for (let i = 0; i < s.length; i += 72) out.push(`  "${s.slice(i, i + 72)}",`);

  return out.join("\n");
};

const HEAD = "// Generated by bin/gate-fonts.mjs from static/fonts/\n"
  + "// aller-regular.woff2 and aller-bold.woff2. Do not edit; run the\n"
  + "// script again.";

export const render = () => `${HEAD}

export const regular = [
${pieces(font("regular"))}
].join("");

export const bold = [
${pieces(font("bold"))}
].join("");
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(root, OUT), render());
  console.log(`Wrote ${OUT}`);
}
