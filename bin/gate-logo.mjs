#!/usr/bin/env node
// Writes netlify/functions/lib/gate-logo.mjs: the site's hen and
// wordmark (assets/images/logo-mark.svg and logo.svg) as strings, for
// the gate's sign-in page (#294). That page is served before anyone
// is signed in, by the edge as well as a function, so it can fetch
// nothing of the site's and carries the logo inline. The SVGs stay the
// one source: test/gate-page.test.mjs fails when this module no longer
// matches them, and running this again fixes it.
//
//   node bin/gate-logo.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const OUT = "netlify/functions/lib/gate-logo.mjs";

const svg = (name) => readFileSync(
  join(root, "assets/images", `${name}.svg`), "utf8"
).trim().replace(/\s*\n\s*/g, " ");

// A long string as lines that keep to 80 columns.
const pieces = (s) => {
  const out = [];

  // 64 leaves room for the quotes JSON adds around a class name.
  for (let i = 0; i < s.length; i += 64) out.push(s.slice(i, i + 64));

  return out.map((p) => `  ${JSON.stringify(p)},`).join("\n");
};

const HEAD = "// Generated by bin/gate-logo.mjs from assets/images/\n"
  + "// logo-mark.svg and logo.svg. Do not edit; run the script again.";

export const render = () => `${HEAD}

export const mark = [
${pieces(svg("logo-mark"))}
].join("");

export const wordmark = [
${pieces(svg("logo"))}
].join("");
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(root, OUT), render());
  console.log(`Wrote ${OUT}`);
}
